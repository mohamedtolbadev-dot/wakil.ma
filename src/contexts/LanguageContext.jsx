// ─── Provider ────────────────────────────────────────────────────────────────

export function LanguageProvider({ children }) {
  const language = useSyncExternalStore(subscribeLanguage, readLanguageSnapshot, () => "fr")

  // Sync html[lang] and html[dir] whenever language changes
  useEffect(() => {
    const isAr = language === "ar"
    document.documentElement.lang = language
    document.documentElement.dir  = isAr ? "rtl" : "ltr"
    syncLanguageCookie(language)
  }, [language])

  const setLanguage = useCallback((lang) => {
    updateLanguagePreference(lang)
  }, [])

  const t = useCallback(
    (key, vars = {}) => {
      const val = translations[language]?.[key] ?? translations["fr"]?.[key] ?? key
      return Object.entries(vars).reduce(
        (s, [k, v]) => s.replace(`{${k}}`, v),
        val
      )
    },
    [language]
  )

  const isRTL  = language === "ar"
  const dir    = isRTL ? "rtl" : "ltr"
  const locale = language === "ar" ? "ar-MA" : "fr-FR"

  return (
    <LanguageContext.Provider value={{ language, setLanguage, t, dir, isRTL, locale }}>
      {children}
    </LanguageContext.Provider>
  )
}

export const useLanguage = () => useContext(LanguageContext)
